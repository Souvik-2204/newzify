import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const built = resolve('client/dist');
const publicDir = resolve('public');
const html = await readFile(resolve(built, 'index.html'), 'utf8');
async function filesUnder(prefix) {
  const entries = await readdir(resolve(built, prefix), { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((entry) => {
        const name = `${prefix}/${entry.name}`;
        if (entry.isDirectory()) return filesUnder(name);
        return entry.isFile() ? [name] : [];
      }),
    )
  ).flat();
}
const files = [
  'favicon.svg',
  ...(await Promise.all(['assets', 'fonts', 'images'].map(filesUnder))).flat(),
].sort();
const images = files.filter((file) => file.startsWith('images/')).map((file) => '/' + file);
const refs = [...html.matchAll(/(?:src|href)="(\/(?:assets\/[^" ]+|favicon\.svg))"/g)].map((m) =>
  m[1].slice(1),
);
if (
  !refs.some((file) => file.endsWith('.js')) ||
  !refs.some((file) => file.endsWith('.css')) ||
  refs.some((file) => !files.includes(file)) ||
  !images.length
)
  throw Error('The built newspaper assets are missing.');
await mkdir(publicDir, { recursive: true });
// Copy only build output. Keep index.html out of the CDN so Express serves article metadata.
for (const name of ['assets', 'fonts', 'images', 'favicon.svg']) {
  const target = resolve(publicDir, name);
  await rm(target, { force: true, recursive: true });
  await cp(resolve(built, name), target, { recursive: true });
}
// Literal URL references let Vercel's function file tracer include every built file.
// Only the public build assets are referenced, never .env, the database or uploads.
const assets = files
  .map(
    (file) =>
      `  [${JSON.stringify('/' + file)}, new URL(${JSON.stringify('../client/dist/' + file)}, import.meta.url)],`,
  )
  .join('\n');
await writeFile(
  'server/generated-web.mjs',
  `// Generated by npm run build:vercel.\nconst files = new Map([\n${assets}\n]);\nexport default { ...${JSON.stringify({ html, images })}, files };\n`,
);
console.log(
  `Prepared ${files.length} Vercel web assets and Express HTML (${images.length} built-in images).`,
);
